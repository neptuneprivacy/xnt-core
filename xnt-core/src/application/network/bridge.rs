use std::io;

use futures::AsyncRead;
use futures::AsyncWrite;
use futures::Sink;
use futures::Stream;
use tokio_serde::SymmetricallyFramed;
use tokio_util::codec::Framed;
use tokio_util::compat::FuturesAsyncReadCompatExt;

use crate::application::loops::connect_to_peers::get_bincode_codec;
use crate::application::loops::connect_to_peers::get_codec_rules;
use crate::protocol::peer::PeerMessage;

/// A transport-agnostic wrapper for peer communication.
///
/// `PeerStream` abstracts away the difference between a standard TCP connection
/// and a libp2p multiplexed stream. This allows the core XNT logic to operate
/// on a unified interface regardless of how the connection was established.
///
/// This trait is used to erase the complex, nested types generated by
/// `tokio_util::codec::Framed` and `tokio_serde` combinators. It provides a
/// unified type that satisfies the `S` bound of the peer loop, specifically
/// requiring:
/// - Bidirectional communication ([`Sink`] + [`Stream`]).
/// - Serialization of [`PeerMessage`] using `io::Error` for transport failures.
/// - Thread-safety ([`Send`]) and stack-stability ([`Unpin`]) for asynchronous
///   execution.
pub(crate) trait PeerStream:
    Stream<Item = Result<PeerMessage, io::Error>> + Sink<PeerMessage, Error = io::Error> + Unpin + Send
{
}

/// Blanket implementation to facilitate automatic type conversion.
///
/// Any type `T`—typically a [`tokio_util::codec::Framed`] instance or a
/// pinned combinator—that fulfills the required networking and safety
/// bounds is automatically categorized as a [`PeerStream`].
impl<T> PeerStream for T where
    T: Stream<Item = Result<PeerMessage, io::Error>>
        + Sink<PeerMessage, Error = io::Error>
        + Unpin
        + Send
{
}

/// Adapts a raw [`libp2p::Stream`] into a [`PeerStream`], on which the
/// handshake has already been exchanged.
///
/// The stream is framed and encoded exactly like a connection of the legacy
/// TCP stack, so that the peer loop treats both alike:
///
/// 1. **IO Compatibility**: Bridges `futures::io` ---> `tokio::io` using
///    `.compat()`.
/// 2. **Framing**: Applies length-delimited framing with per-kind frame limits
///    via [`get_codec_rules`].
/// 3. **Serialization**: Encodes and decodes [`PeerMessage`]s with bincode via
///    [`get_bincode_codec`].
///
/// The handshake was exchanged by the
/// [`HandshakeUpgrade`](super::handshake::HandshakeUpgrade) before the stream
/// gets here, so the frame limit for handshake messages is lifted at once.
/// Without that, every frame would be held to 64 KiB, and blocks and
/// transactions would be refused.
pub(crate) fn bridge_libp2p_stream<S>(raw_stream: S) -> impl PeerStream
where
    S: AsyncRead + AsyncWrite + Unpin + Send,
{
    let framed_bytes = Framed::new(raw_stream.compat(), get_codec_rules());
    let mut peer_stream = SymmetricallyFramed::new(framed_bytes, get_bincode_codec());
    peer_stream.get_mut().codec_mut().complete_handshake();

    peer_stream
}

#[cfg(test)]
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    use bincode::Options;
    use futures::SinkExt;
    use futures::StreamExt;
    use tokio::io::AsyncWriteExt;
    use tokio_util::compat::TokioAsyncReadCompatExt;

    use super::*;
    use crate::application::config::network::Network;
    use crate::application::loops::frame_codec::OversizedFrame;
    use crate::application::network::handshake::HandshakeUpgrade;
    use crate::protocol::consensus::block::Block;
    use crate::protocol::consensus::transaction::validity::neptune_proof::Proof;
    use crate::protocol::peer::transfer_block::TransferBlock;
    use crate::protocol::peer::PeerMessageKind;
    use crate::tests::shared::globalstate::get_dummy_handshake_data_for_genesis;
    use crate::MAGIC_STRING_REQUEST;

    /// A frame as the legacy TCP stack writes it.
    fn frame(message: &PeerMessage) -> Vec<u8> {
        let payload = bincode::DefaultOptions::new().serialize(message).unwrap();
        let mut frame = u32::try_from(payload.len()).unwrap().to_be_bytes().to_vec();
        frame.extend(payload);
        frame
    }

    /// A block message whose frame exceeds the handshake limit of 64 KiB.
    fn large_block_message() -> PeerMessage {
        let network = Network::Main;
        let genesis = Block::genesis(network);
        let block = TransferBlock {
            header: genesis.kernel.header,
            body: genesis.kernel.body.clone(),
            appendix: genesis.kernel.appendix.clone(),
            proof: Proof::invalid_with_size(200_000),
        };
        PeerMessage::Block(Box::new(block))
    }

    #[tokio::test]
    async fn messages_round_trip() {
        let (alice, bob) = tokio::io::duplex(1 << 20);
        let mut alice = bridge_libp2p_stream(alice.compat());
        let mut bob = bridge_libp2p_stream(bob.compat());
        for msg in [
            PeerMessage::BlockNotificationRequest,
            PeerMessage::Bye,
            large_block_message(),
        ] {
            alice.send(msg.clone()).await.unwrap();
            assert_eq!(msg, bob.next().await.unwrap().unwrap());
        }
    }

    #[tokio::test]
    async fn bridged_frames_are_legacy_frames() {
        let (alice, mut bob) = tokio::io::duplex(1 << 20);
        let mut alice = bridge_libp2p_stream(alice.compat());

        let message = PeerMessage::PeerListRequest;
        alice.send(message.clone()).await.unwrap();
        drop(alice);

        let mut received = vec![];
        tokio::io::AsyncReadExt::read_to_end(&mut bob, &mut received)
            .await
            .unwrap();
        assert_eq!(frame(&message), received);
    }

    #[tokio::test]
    async fn an_oversized_frame_is_reported_through_the_bridge() {
        let (mut alice, bob) = tokio::io::duplex(1 << 20);
        let mut bob = bridge_libp2p_stream(bob.compat());

        let mut frame = (100u32 * 1024 * 1024).to_be_bytes().to_vec();
        frame.extend(
            bincode::DefaultOptions::new()
                .serialize(&PeerMessage::Bye)
                .unwrap(),
        );
        alice.write_all(&frame).await.unwrap();

        let error = bob.next().await.unwrap().unwrap_err();
        let oversized = OversizedFrame::behind(&error).unwrap();
        assert_eq!(PeerMessageKind::Bye, oversized.kind);
    }

    #[tokio::test]
    async fn message_sent_with_the_handshake_reaches_the_peer_loop_intact() {
        let network = Network::Main;
        let opener = get_dummy_handshake_data_for_genesis(network);
        let acceptor = get_dummy_handshake_data_for_genesis(network);
        let block_message = large_block_message();

        // The opener's handshake and a large block in a single write, as a
        // peer may send them.
        let mut handshake_frame = frame(&PeerMessage::Handshake {
            magic_value: *MAGIC_STRING_REQUEST,
            data: Box::new(opener),
        });
        let block_frame = frame(&block_message);
        assert!(block_frame.len() > 64 * 1024);
        handshake_frame.extend(&block_frame);

        let (mut opener_socket, acceptor_socket) = tokio::io::duplex(1 << 22);
        let send = async {
            opener_socket.write_all(&handshake_frame).await.unwrap();
            opener_socket
        };
        let accept = HandshakeUpgrade {
            local_handshake: acceptor,
        }
        .accept(acceptor_socket.compat());
        let (_opener_socket, accepted) = tokio::join!(send, accept);

        let (remote_handshake, stream) = accepted.unwrap();
        assert_eq!(opener.instance_id, remote_handshake.instance_id);

        let mut peer_stream = bridge_libp2p_stream(stream);
        assert_eq!(block_message, peer_stream.next().await.unwrap().unwrap());
    }
}
